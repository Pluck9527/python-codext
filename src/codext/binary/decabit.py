def decabit_encode(text, errors="strict"):
    result = []
    for char in ensure_str(text):
        if ord(char) > 126:
            raise ValueError("Decabit only represents ASCII values 0 through 126")
        result.append(CODES[ord(char)])
    output = " ".join(result)
    return output, len(ensure_str(text))


def decabit_decode(text, errors="strict"):
    inverse = {code: chr(value) for value, code in enumerate(CODES)}
    groups = re.findall(r"[+-]{10}", ensure_str(text))
    if not groups and ensure_str(text).strip():
        raise ValueError("Decabit input has no 10-pulse groups")
    if any(group not in inverse for group in groups):
        raise ValueError("unknown Decabit pulse group")
    result = "".join(inverse[group] for group in groups)
    return result, len(ensure_str(text))


add("decabit", decabit_encode, decabit_decode, r"^(?:decabit|deca[-_]?bit)$")
